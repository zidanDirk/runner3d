import { expect, test } from '@playwright/test';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

test('production homepage, free appearance, guidance and real preferences work without developer hooks', async ({ page }) => {
  const errors: string[] = [], models: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).pathname.endsWith('.glb')) models.push(request.url()); });
  await page.goto('/');
  await expect(page.getByRole('button', { name: '开始奔跑', exact: true })).toBeEnabled();
  await expect(page.locator('.character-preview')).toHaveAttribute('data-model-status', 'loaded');
  await expect(page.locator('canvas')).toHaveCount(1);
  expect(models).toHaveLength(1);
  expect(new URL(models[0] ?? '').pathname).toMatch(/\/city-runner\.glb$/);
  expect(await page.evaluate(() => '__RUNNER_TEST__' in window || '__PRODUCT_LIFECYCLE__' in window)).toBe(false);
  await page.getByRole('button', { name: '查看引导', exact: true }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByRole('button', { name: '完成引导', exact: true }).click();
  await expect(page.getByText('初次上路？', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '角色外观', exact: true }).click();
  await page.getByRole('radio', { name: 'Midnight Violet', exact: true }).check();
  await page.getByRole('button', { name: '向右旋转角色', exact: true }).click();
  await page.getByRole('button', { name: '确认外观', exact: true }).click();
  await expect(page.locator('.character-preview')).toHaveAttribute('data-skin-id', 'midnight-violet');
  expect(models.filter(url => new URL(url).pathname.endsWith('/city-runner.glb'))).toHaveLength(1);
  await page.getByRole('button', { name: '游戏设置', exact: true }).click();
  await page.getByLabel('画质', { exact: true }).selectOption('low');
  await page.getByLabel('设置减少动态效果', { exact: true }).check();
  await page.getByLabel('设置音效音量', { exact: true }).fill('35');
  await page.getByRole('button', { name: '关闭设置', exact: true }).click();
  await expect(page.locator('.character-preview__motion-note')).toContainText('静止预览');
  await page.reload();
  await expect(page.locator('.character-preview')).toHaveAttribute('data-skin-id', 'midnight-violet');
  await expect(page.getByText('初次上路？', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '游戏设置', exact: true }).click();
  await expect(page.getByLabel('画质', { exact: true })).toHaveValue('low');
  await expect(page.getByLabel('设置音效音量', { exact: true })).toHaveValue('35');
  await expect(page.getByLabel('设置减少动态效果', { exact: true })).toBeChecked();
  await page.getByRole('button', { name: '关闭设置', exact: true }).click();
  await page.getByRole('button', { name: '开始奔跑', exact: true }).click();
  await expect.poll(async () => Number((await page.getByTestId('distance').innerText()).replaceAll(',', ''))).toBeGreaterThan(2);
  await expect(page.locator('canvas')).toHaveCount(1);
  await page.getByRole('button', { name: '暂停游戏', exact: true }).click();
  await page.getByRole('button', { name: '返回首页', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '离开本局？', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '确认退出', exact: true }).click();
  await expect(page.locator('.home-screen')).toBeVisible();
  await expect(page.getByTestId('wallet')).toHaveText('0');
  expect(errors).toEqual([]);
});

test('production bundle strips product lifecycle probes and keeps scene loading separate from the home entry', async () => {
  const files = readdirSync('dist/assets').filter(name => name.endsWith('.js'));
  const bundle = files.map(name => readFileSync(join('dist/assets', name), 'utf8')).join('\n');
  for (const token of ['__PRODUCT_RESOURCES__', '__PRODUCT_PREVIEW__', '__PRODUCT_LIFECYCLE__', '__RUNNER_TEST__', '__RUNNER_RENDER__', 'installCaptureHooks']) expect(bundle).not.toContain(token);
  expect(files.some(name => name.startsWith('CharacterPreview-'))).toBe(true);
  expect(files.some(name => name.startsWith('GameSession-'))).toBe(true);
});
